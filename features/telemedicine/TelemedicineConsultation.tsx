export const TelemedicineConsultation: React.FC = () => {
  const localControllerRef = useRef(new LocalMediaController());
  const aiService = useRef(new TeleconsultAIService());

  const [session, setSession] = useState<TeleconsultaSession | null>(null);
  const [currentParticipant, setCurrentParticipant] = useState<TeleconsultaParticipant | null>(null);
  const [participants, setParticipants] = useState<Record<string, TeleconsultaParticipant>>({});
  const [localParticipant, setLocalParticipant] = useState<ParticipantDisplay>(DEFAULT_LOCAL_PARTICIPANT);
  const [localStream, setLocalStream] = useState<MediaStream | null>(null);
  const [remoteStream, setRemoteStream] = useState<MediaStream | null>(null);
  const [connectionQuality, setConnectionQuality] = useState<ConnectionQuality>(DEFAULT_CONNECTION_QUALITY);
  const [messages, setMessages] = useState<TelemedicineChatMessage[]>([]);
  const [notes, setNotes] = useState<SessionNote[]>([]);
  const [isCallActive, setIsCallActive] = useState(false);
  const [isCloudMode, setIsCloudMode] = useState(false);
  const [isVideoEnabled, setIsVideoEnabled] = useState(true);
  const [isAudioEnabled, setIsAudioEnabled] = useState(true);
  const [isRecording, setIsRecording] = useState(false);
  const [showChat, setShowChat] = useState(false);
  const [showNotes, setShowNotes] = useState(true);
  const [isConnecting, setIsConnecting] = useState(false);

  const remoteParticipant = useMemo(() => {
    const values = Object.values(participants);
    const remote = values.find(p => p.id !== currentParticipant?.id);
    return remote
      ? {
          id: remote.id,
          name: remote.name,
          role: remote.role,
          isLocal: false,
        }
      : null;
  }, [participants, currentParticipant]);

  useEffect(() => {
    webrtcTeleconsultaService.onRemoteStreamAdded = (_, stream) => {
      setRemoteStream(stream);
    };

    webrtcTeleconsultaService.onParticipantJoined = participant => {
      setParticipants(prev => ({ ...prev, [participant.id]: participant }));
      if (participant.role === 'therapist') {
        setLocalParticipant({
          id: participant.id,
          name: participant.name,
          role: participant.role,
          isLocal: true,
        });
      }
    };

    webrtcTeleconsultaService.onParticipantLeft = participantId => {
      setParticipants(prev => {
        const updated = { ...prev };
        delete updated[participantId];
        return updated;
      });
      if (remoteParticipant?.id === participantId) {
        setRemoteStream(null);
      }
    };

    webrtcTeleconsultaService.onChatMessage = message => {
      const uiMessage = mapRemoteMessageToUI(message);
      setMessages(prev => (prev.some(m => m.id === uiMessage.id) ? prev : [...prev, uiMessage]));
    };

    webrtcTeleconsultaService.onNetworkQuality = metrics => {
      setConnectionQuality(mapNetworkQuality(metrics));
    };

    return () => {
      webrtcTeleconsultaService.onRemoteStreamAdded = undefined;
      webrtcTeleconsultaService.onParticipantJoined = undefined;
      webrtcTeleconsultaService.onParticipantLeft = undefined;
      webrtcTeleconsultaService.onChatMessage = undefined;
      webrtcTeleconsultaService.onNetworkQuality = undefined;
    };
  }, [remoteParticipant]);

  useEffect(() => {
    if (isCloudMode || !isCallActive) {
      return;
    }

    const interval = setInterval(() => {
      setConnectionQuality(localControllerRef.current.getConnectionQuality());
    }, 2000);

    return () => clearInterval(interval);
  }, [isCloudMode, isCallActive]);

  const injectAiNotes = useCallback(async () => {
    try {
      const transcription = await aiService.current.transcribeSession();
      const generated = await aiService.current.generateSOAPNote(transcription);
      const keyMoments = await aiService.current.detectKeyMoments(transcription);
      setNotes(prev => [...prev, ...generated, ...keyMoments]);
    } catch (error) {
      console.warn('Falha ao gerar notas automáticas', error);
    }
  }, []);

  const startCall = useCallback(async () => {
    if (isConnecting) {
      return;
    }

    setIsConnecting(true);
    setConnectionQuality(DEFAULT_CONNECTION_QUALITY);

    try {
      const createdSession = await webrtcTeleconsultaService.createTeleconsultaSession(
        'APPOINTMENT-MOCK',
        'PATIENT-001',
        'THERAPIST-001',
        { recording: true },
      );

      setSession(createdSession);

      const participant = await webrtcTeleconsultaService.joinSession(createdSession.id, {
        userId: 'therapist-001',
        name: 'Dr. Rafael Minatto',
        role: 'therapist',
        email: 'dr.minatto@dudufisio.com',
      });

      setCurrentParticipant(participant);
      setParticipants({ [participant.id]: participant });
      setLocalParticipant({
        id: participant.id,
        name: participant.name,
        role: participant.role,
        isLocal: true,
      });

      const stream = webrtcTeleconsultaService.getLocalStream();
      if (stream) {
        setLocalStream(stream);
      }

      setIsCloudMode(true);
      setIsCallActive(true);
      void injectAiNotes();
    } catch (cloudError) {
      console.warn('Modo cloud indisponível. Ativando fallback local.', cloudError);
      try {
        const stream = await localControllerRef.current.initializeLocalStream({
          cameraId: undefined,
          microphoneId: undefined,
          speakerId: undefined,
          videoEnabled: true,
          audioEnabled: true,
          resolution: '720p',
        });
        setLocalStream(stream);
        setIsCloudMode(false);
        setIsCallActive(true);
        setLocalParticipant(DEFAULT_LOCAL_PARTICIPANT);
        setSession(null);
        setCurrentParticipant(null);
        void injectAiNotes();
      } catch (fallbackError) {
        console.error('Erro ao inicializar teleconsulta', fallbackError);
        alert('Não foi possível iniciar a teleconsulta. Verifique permissões de câmera/microfone.');
      }
    } finally {
      setIsConnecting(false);
    }
  }, [injectAiNotes, isConnecting]);

  const endCall = useCallback(async () => {
    if (isCloudMode) {
      await webrtcTeleconsultaService.leaveSession();
    } else {
      localControllerRef.current.disconnect();
    }

    setIsCallActive(false);
    setIsRecording(false);
    setLocalStream(null);
    setRemoteStream(null);
    setParticipants({});
    setSession(null);
    setCurrentParticipant(null);
    setConnectionQuality(DEFAULT_CONNECTION_QUALITY);
  }, [isCloudMode]);

  const toggleVideo = useCallback(async () => {
    const next = !isVideoEnabled;
    setIsVideoEnabled(next);

    if (isCloudMode) {
      await webrtcTeleconsultaService.toggleVideo(next);
    } else {
      localControllerRef.current.toggleVideo(next);
    }
  }, [isCloudMode, isVideoEnabled]);

  const toggleAudio = useCallback(async () => {
    const next = !isAudioEnabled;
    setIsAudioEnabled(next);

    if (isCloudMode) {
      await webrtcTeleconsultaService.toggleAudio(next);
    } else {
      localControllerRef.current.toggleAudio(next);
    }
  }, [isCloudMode, isAudioEnabled]);

  const toggleRecording = useCallback(async () => {
    const next = !isRecording;

    try {
      if (next) {
        if (isCloudMode && session && currentParticipant) {
          await webrtcTeleconsultaService.startRecording(session.id, currentParticipant.id);
        } else {
          await localControllerRef.current.startRecording();
        }
      } else {
        if (isCloudMode) {
          await webrtcTeleconsultaService.stopRecording();
        } else {
          const blob = localControllerRef.current.stopRecording();
          if (blob) {
            console.info('Gravação local concluída', blob.size, 'bytes');
          }
        }
      }

      setIsRecording(next);
    } catch (error) {
      console.error('Erro ao alternar gravação', error);
      alert('Não foi possível alterar o estado da gravação.');
    }
  }, [currentParticipant, isCloudMode, isRecording, session]);

  const sendMessage = useCallback(
    async (message: string) => {
      const senderId = currentParticipant?.userId ?? 'therapist-local';
      const senderName = currentParticipant?.name ?? 'Profissional';

      const optimistic = createOptimisticMessage(senderId, senderName, message);
      setMessages(prev => [...prev, optimistic]);

      if (!isCloudMode || !session || !currentParticipant) {
        return;
      }

      try {
        const savedMessage = await webrtcTeleconsultaService.sendChatMessage(
          session.id,
          currentParticipant.userId,
          currentParticipant.name,
          message,
        );

        const formatted = mapRemoteMessageToUI(savedMessage);

        setMessages(prev => {
          const replaced = prev.map(msg => (msg.id === optimistic.id ? formatted : msg));
          if (replaced.some(msg => msg.id === formatted.id)) {
            return replaced;
          }
          return replaced.concat(formatted);
        });
      } catch (error) {
        console.warn('Não foi possível enviar mensagem para o servidor', error);
        setMessages(prev =>
          prev.map(msg =>
            msg.id === optimistic.id
              ? { ...msg, type: 'system', message: `${msg.message} (não sincronizado)` }
              : msg,
          ),
        );
      }
    },
    [currentParticipant, isCloudMode, session],
  );

  const addNote = useCallback((note: Omit<SessionNote, 'timestamp'>) => {
    setNotes(prev => [
      ...prev,
      {
        ...note,
        timestamp: new Date(),
        source: 'manual',
      },
    ]);
  }, []);

  const exportNotes = useCallback(() => {
    if (typeof window === 'undefined') {
      return;
    }

    const payload = notes.map(note => ({
      ...note,
      timestamp: note.timestamp.toISOString(),
    }));

    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);

    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = `teleconsulta-notas-${Date.now()}.json`;
    anchor.click();

    URL.revokeObjectURL(url);
  }, [notes]);

  if (!isCallActive) {
    return (
      <div className="flex items-center justify-center h-screen bg-gradient-to-br from-blue-500 to-purple-600">
        <div className="bg-white rounded-2xl shadow-2xl p-12 max-w-md w-full text-center space-y-6">
          <Video className="w-24 h-24 text-blue-600 mx-auto" />
          <div>
            <h1 className="text-3xl font-bold text-gray-900">Teleconsulta</h1>
            <p className="text-gray-600 mt-2">
              Conecte pacientes em qualquer lugar com qualidade clínica e recursos avançados.
            </p>
          </div>

          <div className="grid grid-cols-2 gap-4 text-left">
            <div className="p-3 bg-blue-50 rounded-lg">
              <CheckCircle className="w-5 h-5 text-blue-600" />
              <p className="text-sm text-gray-700 mt-2">Videochamada HD com fallback offline</p>
            </div>
            <div className="p-3 bg-blue-50 rounded-lg">
              <Activity className="w-5 h-5 text-blue-600" />
              <p className="text-sm text-gray-700 mt-2">Anotações automáticas com IA</p>
            </div>
            <div className="p-3 bg-blue-50 rounded-lg">
              <MessageSquare className="w-5 h-5 text-blue-600" />
              <p className="text-sm text-gray-700 mt-2">Chat seguro e arquivos</p>
            </div>
            <div className="p-3 bg-blue-50 rounded-lg">
              <AlertCircle className="w-5 h-5 text-blue-600" />
              <p className="text-sm text-gray-700 mt-2">Monitoramento de rede em tempo real</p>
            </div>
          </div>

          <button
            onClick={startCall}
            disabled={isConnecting}
            className={`w-full px-8 py-4 rounded-lg text-white font-semibold text-lg transition ${
              isConnecting ? 'bg-gray-400 cursor-not-allowed' : 'bg-green-600 hover:bg-green-700'
            }`}
          >
            {isConnecting ? 'Conectando…' : 'Iniciar Teleconsulta'}
          </button>

          <p className="text-xs text-gray-500">
            LGPD • Resolução CFM nº 2.314/2022 • Criptografia ponta-a-ponta
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="h-screen flex flex-col bg-gray-100">
      <div className="bg-white border-b px-6 py-3 flex items-center justify-between">
        <div className="flex items-center space-x-3">
          <div className="w-2 h-2 bg-green-500 rounded-full animate-pulse" />
          <span className="font-semibold text-gray-900">Teleconsulta em andamento</span>
          <span
            className={`text-xs px-2 py-1 rounded-full ${
              isCloudMode ? 'bg-blue-100 text-blue-700' : 'bg-gray-200 text-gray-700'
            }`}
          >
            {isCloudMode ? 'Modo Online (WebRTC)' : 'Modo Local (Fallback)'}
          </span>
        </div>
        <div className="flex items-center space-x-4 text-sm text-gray-600">
          <div className="flex items-center space-x-1">
            <Clock className="w-4 h-4" />
            <span>{new Date().toLocaleTimeString('pt-BR')}</span>
          </div>
          {isRecording && (
            <div className="flex items-center space-x-1 text-red-600">
              <div className="w-2 h-2 bg-red-600 rounded-full animate-pulse" />
              <span>Gravando</span>
            </div>
          )}
        </div>
      </div>

      <div className="flex-1 flex overflow-hidden">
        <div className="flex-1 p-4">
          <VideoGrid
            localStream={localStream}
            remoteStream={remoteStream}
            localParticipant={localParticipant}
            remoteParticipant={remoteParticipant}
            connectionQuality={connectionQuality}
          />
        </div>

        {(showChat || showNotes) && (
          <div className="w-96 border-l bg-white">
            {showChat && <SidebarChat messages={messages} onSendMessage={sendMessage} />}
            {showNotes && <SessionNotes notes={notes} onAddNote={addNote} onExportNotes={exportNotes} />}
          </div>
        )}
      </div>

      <ControlBar
        isVideoEnabled={isVideoEnabled}
        isAudioEnabled={isAudioEnabled}
        isRecording={isRecording}
        onToggleVideo={toggleVideo}
        onToggleAudio={toggleAudio}
        onToggleRecording={toggleRecording}
        onEndCall={endCall}
        onOpenChat={() => {
          setShowChat(prev => !prev);
          if (!showChat) {
            setShowNotes(false);
          }
        }}
        onOpenNotes={() => {
          setShowNotes(prev => !prev);
          if (!showNotes) {
            setShowChat(false);
          }
        }}
        onShareScreen={() => {
          if (isCloudMode && currentParticipant) {
            webrtcTeleconsultaService.startScreenShare(currentParticipant.id).catch(error =>
              alert(`Não foi possível iniciar compartilhamento de tela: ${
                error instanceof Error ? error.message : error
              }`),
            );
          } else {
            alert('Compartilhamento de tela disponível apenas no modo online.');
          }
        }}
        onSettings={() => alert('Configurações avançadas em desenvolvimento.')}
        isChatOpen={showChat}
        isNotesOpen={showNotes}
      />
    </div>
  );
};

export default TelemedicineConsultation;
