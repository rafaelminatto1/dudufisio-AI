class LocalMediaController {
  private localStream: MediaStream | null = null;
  private mediaRecorder: MediaRecorder | null = null;
  private recordedChunks: Blob[] = [];

  async initializeLocalStream(settings: DeviceSettings): Promise<MediaStream> {
    if (typeof navigator === 'undefined' || !navigator.mediaDevices?.getUserMedia) {
      throw new Error('Dispositivo não suporta captura de mídia');
    }

    const constraints: MediaStreamConstraints = {
      video: settings.videoEnabled
        ? {
            deviceId: settings.cameraId ? { exact: settings.cameraId } : undefined,
            width: { ideal: settings.resolution === '1080p' ? 1920 : 1280 },
            height: { ideal: settings.resolution === '1080p' ? 1080 : 720 },
            frameRate: { ideal: 30 },
          }
        : false,
      audio: settings.audioEnabled
        ? {
            deviceId: settings.microphoneId ? { exact: settings.microphoneId } : undefined,
            echoCancellation: true,
            noiseSuppression: true,
            autoGainControl: true,
          }
        : false,
    };

    this.localStream = await navigator.mediaDevices.getUserMedia(constraints);
    return this.localStream;
  }

  toggleVideo(enabled: boolean) {
    this.localStream?.getVideoTracks().forEach(track => {
      track.enabled = enabled;
    });
  }

  toggleAudio(enabled: boolean) {
    this.localStream?.getAudioTracks().forEach(track => {
      track.enabled = enabled;
    });
  }

  async startRecording(): Promise<void> {
    if (typeof MediaRecorder === 'undefined') {
      console.warn('MediaRecorder não disponível neste navegador');
      return;
    }

    if (!this.localStream) {
      throw new Error('Nenhuma stream local disponível para gravação');
    }

    this.recordedChunks = [];
    this.mediaRecorder = new MediaRecorder(this.localStream, {
      mimeType: 'video/webm;codecs=vp8,opus',
      videoBitsPerSecond: 2_000_000,
      audioBitsPerSecond: 128_000,
    });

    this.mediaRecorder.ondataavailable = event => {
      if (event.data.size > 0) {
        this.recordedChunks.push(event.data);
      }
    };

    this.mediaRecorder.start(1000);
  }

  stopRecording(): Blob | null {
    if (this.mediaRecorder?.state === 'recording') {
      this.mediaRecorder.stop();
    }

    if (this.recordedChunks.length === 0) {
      return null;
    }

    const blob = new Blob(this.recordedChunks, { type: 'video/webm' });
    this.recordedChunks = [];
    return blob;
  }

  disconnect(): void {
    this.localStream?.getTracks().forEach(track => track.stop());
    this.localStream = null;
    this.mediaRecorder = null;
    this.recordedChunks = [];
  }

  getLocalStream(): MediaStream | null {
    return this.localStream;
  }

  getConnectionQuality(): ConnectionQuality {
    return {
      bitrate: 1200,
      packetLoss: 0.5,
      latency: 45,
      resolution: '720p',
      status: 'good',
    };
  }
}

const mapNetworkQuality = (metrics: NetworkQualityMetrics): ConnectionQuality => {
  const latency = metrics.latency ?? 0;
  const packetLoss = metrics.packetLoss ?? 0;
  const download = metrics.bandwidth?.download ?? 0;

  let status: ConnectionQuality['status'] = 'excellent';

  if (latency > 250 || packetLoss > 5) {
    status = 'critical';
  } else if (latency > 150 || packetLoss > 3) {
    status = 'poor';
  } else if (latency > 90 || packetLoss > 1.5) {
    status = 'good';
  }

  return {
    bitrate: download,
    packetLoss,
    latency,
    resolution: download > 2500 ? '1080p (adaptativo)' : '720p (adaptativo)',
    status,
  };
};

