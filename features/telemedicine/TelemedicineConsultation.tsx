interface VideoGridProps {
  localStream: MediaStream | null;
  remoteStream: MediaStream | null;
  localParticipant: Participant;
  remoteParticipant: Participant;
  connectionQuality: ConnectionQuality;
}

const VideoGrid: React.FC<VideoGridProps> = ({
  localStream,
  remoteStream,
  localParticipant,
  remoteParticipant,
  connectionQuality,
}) => {
  const localVideoRef = useRef<HTMLVideoElement>(null);
  const remoteVideoRef = useRef<HTMLVideoElement>(null);

  useEffect(() => {
    if (localVideoRef.current && localStream) {
      localVideoRef.current.srcObject = localStream;
    }
  }, [localStream]);

  useEffect(() => {
    if (remoteVideoRef.current && remoteStream) {
      remoteVideoRef.current.srcObject = remoteStream;
    }
  }, [remoteStream]);

  const getQualityColor = (status: string) => {
    switch (status) {
      case 'excellent': return 'bg-green-500';
      case 'good': return 'bg-blue-500';
      case 'poor': return 'bg-yellow-500';
      case 'critical': return 'bg-red-500';
      default: return 'bg-gray-500';
    }
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-4 gap-4 h-full">
      {/* Remote Video (Main) */}
      <div className="lg:col-span-3 relative bg-gray-900 rounded-lg overflow-hidden">
        {remoteStream ? (
          <>
            <video
              ref={remoteVideoRef}
              autoPlay
              playsInline
              className="w-full h-full object-cover"
            />
            <div className="absolute top-4 left-4 bg-black bg-opacity-75 text-white px-3 py-2 rounded-lg">
              <p className="font-semibold">{remoteParticipant.name}</p>
              <p className="text-xs opacity-75">{remoteParticipant.role}</p>
            </div>
          </>
        ) : (
          <div className="flex items-center justify-center h-full text-white">
            <div className="text-center">
              <Users className="w-16 h-16 mx-auto mb-4 opacity-50" />
              <p className="text-lg">Aguardando conexão...</p>
            </div>
          </div>
        )}

        {/* Connection Quality Indicator */}
        <div className="absolute top-4 right-4 flex items-center space-x-2 bg-black bg-opacity-75 px-3 py-2 rounded-lg">
          <div className={`w-3 h-3 rounded-full ${getQualityColor(connectionQuality.status)}`} />
          <span className="text-white text-sm">
            {connectionQuality.latency}ms • {connectionQuality.resolution}
          </span>
        </div>
      </div>

      {/* Local Video (Picture-in-Picture) */}
      <div className="lg:col-span-1 relative bg-gray-800 rounded-lg overflow-hidden aspect-video lg:aspect-auto">
        {localStream ? (
          <>
            <video
              ref={localVideoRef}
              autoPlay
              playsInline
              muted
              className="w-full h-full object-cover transform scale-x-[-1]" // Mirror effect
            />
            <div className="absolute bottom-4 left-4 bg-black bg-opacity-75 text-white px-2 py-1 rounded text-xs">
              Você
            </div>
          </>
        ) : (
          <div className="flex items-center justify-center h-full text-white">
            <VideoOff className="w-8 h-8 opacity-50" />
          </div>
        )}
      </div>
    </div>
  );
};

